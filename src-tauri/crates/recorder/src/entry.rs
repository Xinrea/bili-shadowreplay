use chrono::{TimeZone, Utc};
use core::fmt;
use recording_storage::RecordingStorage;
use std::{fmt::Display, io};
use tokio::io::{AsyncBufReadExt, BufReader};

const ENTRY_FILE_NAME: &str = "entries.log";

#[derive(Clone, Debug)]
pub struct TsEntry {
    pub url: String,
    pub sequence: u64,
    pub length: f64,
    pub size: u64,
    pub ts: i64,
    pub is_header: bool,
}

impl TsEntry {
    pub fn from(line: &str) -> Result<Self, String> {
        let parts: Vec<&str> = line.split('|').collect();
        if parts.len() != 6 {
            return Err("Invalid input format: expected 6 fields separated by '|'".to_string());
        }
        Ok(TsEntry {
            url: parts[0].to_string(),
            sequence: parts[1]
                .parse()
                .map_err(|e| format!("Failed to parse sequence: {e}"))?,
            length: parts[2]
                .parse()
                .map_err(|e| format!("Failed to parse length: {e}"))?,
            size: parts[3]
                .parse()
                .map_err(|e| format!("Failed to parse size: {e}"))?,
            ts: parts[4]
                .parse()
                .map_err(|e| format!("Failed to parse timestamp: {e}"))?,
            is_header: parts[5]
                .parse()
                .map_err(|e| format!("Failed to parse is_header: {e}"))?,
        })
    }

    /// Get timestamp in seconds
    pub fn ts_seconds(&self) -> i64 {
        // For some legacy problem, douyin entry's ts is s, bilibili entry's ts is ms.
        // This should be fixed after 2.5.6, but we need to support entry.log generated by previous version.
        if self.ts > 10_000_000_000 {
            self.ts / 1000
        } else {
            self.ts
        }
    }

    pub fn date_time(&self) -> String {
        let date_str = Utc
            .timestamp_opt(self.ts_seconds(), 0)
            .single()
            .unwrap_or_default()
            .to_rfc3339();
        format!("#EXT-X-PROGRAM-DATE-TIME:{date_str}\n")
    }

    /// Convert entry into a segment in HLS manifest.
    pub fn to_segment(&self) -> String {
        if self.is_header {
            return String::new();
        }

        let mut content = String::new();

        content += &format!("#EXTINF:{:.4},\n", self.length);
        content += &format!("{}\n", self.url);

        content
    }
}

impl Display for TsEntry {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        writeln!(
            f,
            "{}|{}|{}|{}|{}|{}",
            self.url, self.sequence, self.length, self.size, self.ts, self.is_header
        )
    }
}

/// `EntryStore` is used to management stream segments, which is basically a simple version of hls manifest,
/// and of course, provides methods to generate hls manifest for frontend player.
pub struct EntryStore {
    header: Option<TsEntry>,
    entries: Vec<TsEntry>,
    total_duration: f64,
    total_size: u64,
    pub last_sequence: u64,
}

impl EntryStore {
    pub async fn new(work_dir: &str) -> Self {
        let storage = RecordingStorage::local(work_dir);
        if let Err(e) = storage.prepare().await {
            log::error!("Failed to create work dir {work_dir}: {e}");
        }
        match Self::from_storage(&storage).await {
            Ok(entry_store) => entry_store,
            Err(e) => {
                log::error!("Failed to open entry file: {e}");
                Self::empty()
            }
        }
    }

    fn empty() -> Self {
        Self {
            header: None,
            entries: vec![],
            total_duration: 0.0,
            total_size: 0,
            last_sequence: 0,
        }
    }

    pub async fn from_storage(storage: &RecordingStorage) -> io::Result<Self> {
        let mut entry_store = Self::empty();
        let contents = match storage.read_log(ENTRY_FILE_NAME).await {
            Ok(contents) => contents,
            Err(e) if e.kind() == io::ErrorKind::NotFound => {
                log::info!("Entry file {ENTRY_FILE_NAME} not found, starting fresh.");
                return Ok(entry_store);
            }
            Err(e) => return Err(e),
        };
        // Storage exposes whole-object reads; retain the legacy line parser for
        // recordings migrated from entries.log, including CRLF and invalid rows.
        let mut lines = BufReader::new(contents.as_slice()).lines();
        // A malformed UTF-8 tail must not discard the readable legacy prefix.
        while let Ok(Some(line)) = lines.next_line().await {
            let entry = match TsEntry::from(line.as_str()) {
                Ok(entry) => entry,
                Err(e) => {
                    log::error!("Failed to parse entry: {e} {line}");
                    continue;
                }
            };

            entry_store.last_sequence = std::cmp::max(entry_store.last_sequence, entry.sequence);

            if entry.is_header {
                entry_store.header = Some(entry.clone());
            } else {
                entry_store.entries.push(entry.clone());
            }

            entry_store.total_duration += entry.length;
            entry_store.total_size += entry.size;
        }
        Ok(entry_store)
    }

    pub fn len(&self) -> usize {
        self.entries.len()
    }

    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }

    pub fn total_duration(&self) -> f64 {
        self.total_duration
    }

    pub fn total_size(&self) -> u64 {
        self.total_size
    }

    /// Generate a hls manifest for selected range.
    /// `vod` indicates the manifest is for stream or video.
    /// `force_time` adds DATE-TIME tag for each entry.
    pub fn manifest(&self, vod: bool, force_time: bool, range: Option<Range>) -> String {
        let mut m3u8_content = "#EXTM3U\n".to_string();
        m3u8_content += "#EXT-X-VERSION:6\n";
        m3u8_content += if vod {
            "#EXT-X-PLAYLIST-TYPE:VOD\n"
        } else {
            "#EXT-X-PLAYLIST-TYPE:EVENT\n"
        };
        let end_content = if vod { "#EXT-X-ENDLIST" } else { "" };

        let Some(first_entry) = self.entries.first() else {
            m3u8_content += end_content;
            return m3u8_content;
        };

        m3u8_content += &format!(
            "#EXT-X-TARGETDURATION:{}\n",
            (0.5 + first_entry.length).floor()
        );

        // add header, FMP4 need this
        if let Some(header) = &self.header {
            m3u8_content += &format!("#EXT-X-MAP:URI=\"{}\"\n", header.url);
        }

        // Collect entries in range
        let first_entry_ts = first_entry.ts_seconds();
        let mut entries_in_range = vec![];
        for e in &self.entries {
            // ignore header, cause it's already in EXT-X-MAP
            if e.is_header {
                continue;
            }
            let entry_offset = (e.ts_seconds() - first_entry_ts) as f32;
            if range.is_none_or(|r| r.is_in(entry_offset)) {
                entries_in_range.push(e);
            }
        }

        let Some(first_in_range) = entries_in_range.first() else {
            m3u8_content += end_content;
            log::warn!("No entries in range, return empty manifest");
            return m3u8_content;
        };

        let mut previous_seq = first_in_range.sequence;
        for (i, e) in entries_in_range.iter().enumerate() {
            let discontinuous = e.sequence < previous_seq || e.sequence - previous_seq > 1;
            if discontinuous {
                m3u8_content += "#EXT-X-DISCONTINUITY\n";
            }
            // Add date time under these situations.
            if i == 0 || i == entries_in_range.len() - 1 || force_time || discontinuous {
                m3u8_content += &e.date_time();
            }
            m3u8_content += &e.to_segment();

            previous_seq = e.sequence;
        }

        m3u8_content += end_content;
        m3u8_content
    }
}

#[derive(Debug, Clone, Copy)]
pub struct Range {
    pub x: f32,
    pub y: f32,
}

impl Range {
    pub fn is_in(&self, v: f32) -> bool {
        v >= self.x && v <= self.y
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[tokio::test]
    async fn storage_loads_legacy_entries_and_skips_invalid_rows() {
        let dir = tempfile::tempdir().unwrap();
        let storage = RecordingStorage::local(dir.path());
        let contents = b"init.mp4|0|0|512|1700000000|true\r\n\
                         broken row\n\
                         bad.ts|bad|5|100|1700000000|false\n\
                         first.ts|42|5|100|1700000000|false\r\n\
                         last.ts|41|6|200|1700000005000|false";
        storage.write(ENTRY_FILE_NAME, contents).await.unwrap();
        let entries = EntryStore::from_storage(&storage).await.unwrap();
        assert_eq!(entries.len(), 2);
        assert_eq!(entries.last_sequence, 42);
        assert_eq!(entries.total_duration(), 11.0);
        assert_eq!(entries.total_size(), 812);
        assert_eq!(entries.header.as_ref().unwrap().url, "init.mp4");
        assert_eq!(entries.entries[1].ts_seconds(), 1_700_000_005);
        let manifest = entries.manifest(true, false, None);
        assert!(manifest.contains("#EXT-X-MAP:URI=\"init.mp4\""));
        assert!(manifest.contains("#EXT-X-DISCONTINUITY"));
        let wrapped = EntryStore::new(dir.path().to_str().unwrap()).await;
        assert_eq!(wrapped.manifest(true, false, None), manifest);
        assert_eq!(storage.read(ENTRY_FILE_NAME).await.unwrap(), contents);
    }

    #[tokio::test]
    async fn interrupted_utf8_tail_preserves_legacy_entries() {
        let dir = tempfile::tempdir().unwrap();
        let storage = RecordingStorage::local(dir.path());
        storage
            .write(ENTRY_FILE_NAME, b"first.ts|42|5|100|1700000000|false\n\xe4")
            .await
            .unwrap();
        let entries = EntryStore::from_storage(&storage).await.unwrap();
        assert_eq!(entries.len(), 1);
        assert_eq!(entries.last_sequence, 42);
        assert_eq!(entries.total_size(), 100);
        let wrapped = EntryStore::new(dir.path().to_str().unwrap()).await;
        assert_eq!(wrapped.len(), 1);
        assert_eq!(wrapped.last_sequence, 42);
    }

    #[tokio::test]
    async fn missing_entries_start_empty_and_wrapper_prepares_directory() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("new-recording");
        let entries = EntryStore::new(path.to_str().unwrap()).await;
        assert!(entries.is_empty());
        assert!(path.is_dir());
        let storage = RecordingStorage::local(&path);
        assert!(EntryStore::from_storage(&storage).await.unwrap().is_empty());
        assert_eq!(
            storage.read(ENTRY_FILE_NAME).await.unwrap_err().kind(),
            io::ErrorKind::NotFound
        );
    }

    #[tokio::test]
    async fn storage_surfaces_read_failures_and_wrapper_falls_back() {
        let dir = tempfile::tempdir().unwrap();
        let storage = RecordingStorage::local(dir.path());
        std::fs::create_dir(dir.path().join(ENTRY_FILE_NAME)).unwrap();
        assert!(EntryStore::from_storage(&storage).await.is_err());
        assert!(EntryStore::new(dir.path().to_str().unwrap())
            .await
            .is_empty());
        let file_as_directory = dir.path().join("not-a-directory");
        std::fs::write(&file_as_directory, b"unchanged").unwrap();
        assert!(EntryStore::new(file_as_directory.to_str().unwrap())
            .await
            .is_empty());
        assert_eq!(std::fs::read(file_as_directory).unwrap(), b"unchanged");
    }

    #[test]
    fn test_ts_entry_from_valid() {
        let line = "https://example.com/seg.ts|42|5.0|1024|1700000000|false";
        let entry = TsEntry::from(line).unwrap();
        assert_eq!(entry.url, "https://example.com/seg.ts");
        assert_eq!(entry.sequence, 42);
        assert!((entry.length - 5.0).abs() < f64::EPSILON);
        assert_eq!(entry.size, 1024);
        assert_eq!(entry.ts, 1700000000);
        assert!(!entry.is_header);
    }

    #[test]
    fn test_ts_entry_from_header() {
        let line = "https://example.com/init.mp4|0|0.0|512|1700000000|true";
        let entry = TsEntry::from(line).unwrap();
        assert!(entry.is_header);
    }

    #[test]
    fn test_ts_entry_from_invalid_field_count() {
        let line = "a|b|c";
        let result = TsEntry::from(line);
        assert!(result.is_err());
        assert!(result.unwrap_err().contains("expected 6 fields"));
    }

    #[test]
    fn test_ts_entry_from_invalid_number() {
        let line = "url|notanumber|5.0|1024|1700000000|false";
        let result = TsEntry::from(line);
        assert!(result.is_err());
        assert!(result.unwrap_err().contains("Failed to parse sequence"));
    }

    #[test]
    fn test_ts_seconds_milliseconds() {
        let entry = TsEntry {
            url: "test".to_string(),
            sequence: 1,
            length: 5.0,
            size: 100,
            ts: 1700000000000, // ms timestamp
            is_header: false,
        };
        assert_eq!(entry.ts_seconds(), 1700000000);
    }

    #[test]
    fn test_ts_seconds_already_seconds() {
        let entry = TsEntry {
            url: "test".to_string(),
            sequence: 1,
            length: 5.0,
            size: 100,
            ts: 1700000000, // already in seconds
            is_header: false,
        };
        assert_eq!(entry.ts_seconds(), 1700000000);
    }

    #[test]
    fn test_to_segment_normal() {
        let entry = TsEntry {
            url: "segment_001.ts".to_string(),
            sequence: 1,
            length: 5.1234,
            size: 100,
            ts: 1700000000,
            is_header: false,
        };
        let seg = entry.to_segment();
        assert!(seg.contains("#EXTINF:5.1234,"));
        assert!(seg.contains("segment_001.ts"));
    }

    #[test]
    fn test_to_segment_header_returns_empty() {
        let entry = TsEntry {
            url: "init.mp4".to_string(),
            sequence: 0,
            length: 0.0,
            size: 100,
            ts: 1700000000,
            is_header: true,
        };
        assert_eq!(entry.to_segment(), "");
    }

    #[test]
    fn test_date_time_format() {
        let entry = TsEntry {
            url: "test".to_string(),
            sequence: 1,
            length: 5.0,
            size: 100,
            ts: 1700000000,
            is_header: false,
        };
        let dt = entry.date_time();
        assert!(dt.starts_with("#EXT-X-PROGRAM-DATE-TIME:"));
        assert!(dt.contains("2023"));
    }

    #[test]
    fn test_range_is_in() {
        let r = Range { x: 1.0, y: 5.0 };
        assert!(r.is_in(3.0));
        assert!(r.is_in(1.0));
        assert!(r.is_in(5.0));
        assert!(!r.is_in(0.9));
        assert!(!r.is_in(5.1));
    }

    #[test]
    fn test_ts_entry_display() {
        let entry = TsEntry {
            url: "seg.ts".to_string(),
            sequence: 1,
            length: 5.0,
            size: 1024,
            ts: 1700000000,
            is_header: false,
        };
        let display = format!("{}", entry);
        assert!(display.contains("seg.ts"));
        assert!(display.contains("1024"));
    }
}
