use std::net::{IpAddr, Ipv4Addr, SocketAddr};

use serde::{Deserialize, Serialize};

/// Persisted in the recorder's `extra` column, including the generated key.
#[derive(Clone, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct RtmpConfig {
    pub name: String,
    pub listen_addr: IpAddr,
    pub port: u16,
    pub stream_key: String,
}

impl Default for RtmpConfig {
    fn default() -> Self {
        Self {
            name: "RTMP 推流".into(),
            listen_addr: IpAddr::V4(Ipv4Addr::UNSPECIFIED),
            // Zero asks the OS to reserve an available port when we bind.
            port: 0,
            stream_key: uuid::Uuid::new_v4().simple().to_string(),
        }
    }
}

impl RtmpConfig {
    /// Creation accepts only a name; credentials are generated by the server.
    pub fn for_new_room(extra: &str) -> Result<Self, String> {
        #[derive(Deserialize)]
        #[serde(deny_unknown_fields)]
        struct NewRoom {
            name: String,
        }
        let room: NewRoom = serde_json::from_str(extra)
            .map_err(|error| format!("RTMP 配置无效: {error}"))?;
        Self {
            name: room.name,
            ..Self::default()
        }
        .validate()
    }

    pub fn parse(extra: &str) -> Result<Self, String> {
        let config: Self = if extra.trim().is_empty() {
            Self::default()
        } else {
            serde_json::from_str(extra).map_err(|error| format!("RTMP 配置无效: {error}"))?
        };
        config.validate()
    }

    fn validate(mut self) -> Result<Self, String> {
        self.name = self.name.trim().to_string();
        if self.name.is_empty() || self.name.chars().count() > 80 {
            return Err("RTMP 房间名称应为 1–80 个字符".into());
        }
        if self.stream_key.is_empty()
            || self.stream_key.len() > 128
            || !self
                .stream_key
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_')
        {
            return Err("推流密钥应为 1–128 位字母、数字、下划线或连字符".into());
        }
        Ok(self)
    }

    pub fn socket_addr(&self) -> SocketAddr {
        SocketAddr::new(self.listen_addr, self.port)
    }
}

pub fn normalize_room_id(room_id: &str) -> Result<String, String> {
    let room_id = room_id.trim();
    if room_id.is_empty() {
        return Ok(format!("rtmp-{}", uuid::Uuid::new_v4().simple()));
    }
    if room_id.len() > (if room_id.starts_with("rtmp-") { 80 } else { 75 })
        || !room_id
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_')
    {
        return Err("RTMP 房间 ID 只能包含字母、数字、下划线或连字符，最多 80 位".into());
    }
    // Room IDs also identify database archives across platforms.
    Ok(if room_id.starts_with("rtmp-") {
        room_id.to_string()
    } else {
        format!("rtmp-{room_id}")
    })
}
